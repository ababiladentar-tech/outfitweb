/**
 * Writes supabase/seed.sql from the demo data in src/lib/data.ts.
 * Run: npm run db:seed-sql
 */
import { writeFileSync } from 'node:fs';
import { STORES, SEED_PRODUCTS } from '../src/lib/data';

const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  return `'${String(v).replace(/'/g, "''")}'`;
};
const arr = (v: string[]): string => `array[${v.map(q).join(', ')}]::text[]`;
const json = (v: unknown): string => `${q(JSON.stringify(v))}::jsonb`;

const stores = STORES.map(
  (s) =>
    `(${[s.id, s.name, s.city, s.followerCount, s.contactNumber, s.bio, s.story, s.externalShopUrl, s.instagram, s.sellerType, s.bannerHex, s.avatarHex].map(q).join(', ')})`,
);

const products = SEED_PRODUCTS.map(
  (p) =>
    `(${[
      q(p.id), q(p.sellerId), q(p.title), q(p.description), q(p.category), q(p.style), q(p.colorFamily), arr(p.colorHex),
      q(p.price), q(p.originalPrice), q(p.condition), q(!!p.isOneOfAKind), q(p.stockCount), q(p.isAvailable),
      json(p.availableSizes), q(p.imageUrl), q(p.material), q(!!p.stretch), q(p.likes), q(p.saves), arr(p.tags), q(p.createdAt),
    ].join(', ')})`,
);

const sql = `-- Generated by scripts/generate-seed.ts from src/lib/data.ts. Safe to re-run.
-- Demo stores start unclaimed (owner_id null); a signed-in seller can claim one from the dashboard.

insert into public.stores (id, name, city, follower_count, contact_number, bio, story, external_shop_url, instagram, seller_type, banner_hex, avatar_hex)
values
${stores.join(',\n')}
on conflict (id) do update set
  name = excluded.name, city = excluded.city, contact_number = excluded.contact_number, bio = excluded.bio,
  story = excluded.story, external_shop_url = excluded.external_shop_url, instagram = excluded.instagram,
  seller_type = excluded.seller_type, banner_hex = excluded.banner_hex, avatar_hex = excluded.avatar_hex;

insert into public.products (id, store_id, title, description, category, style, color_family, color_hex, price, original_price, condition, is_one_of_a_kind, stock_count, is_available, available_sizes, image_url, material, stretch, likes, saves, tags, created_at)
values
${products.join(',\n')}
on conflict (id) do nothing;
`;

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log(`seed.sql: ${STORES.length} toko, ${SEED_PRODUCTS.length} produk`);
